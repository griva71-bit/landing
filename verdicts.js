/**
 * Собирает блок "Ваши страхи и опасения" из массива выбранных страхов
 * @param {Array<string>} fearsArray - массив ключей страхов из FEAR_RESPONSES
 * @returns {string} HTML-строка с заголовком и ответами на страхи
 */
function buildFearsBlock(fearsArray) {
  if (!fearsArray || fearsArray.length === 0) {
    return '';
  }
  
  const fearsContent = fearsArray
    .map(fearKey => {
      const fear = FEAR_RESPONSES[fearKey];
      if (!fear) return '';
      return `<div class="fear-item">${fear.response}</div>`;
    })
    .filter(html => html !== '')
    .join('\n');
  
  if (!fearsContent) return '';
  
  return `
    <h3>Ваши опасения — разбираем по пунктам</h3>
    <p>Вы отметили несколько страхов. Это нормально — у всех они есть перед первым (и не только первым) заходом. Разберу каждый честно:</p>
    <div class="fears-block">
      ${fearsContent}
    </div>
  `;
}


/**
 * Собирает блок медицинских предупреждений из массива жёлтых флагов
 * @param {Array<string>} yellowFlagsArray - массив ключей из YELLOW_BLOCKS
 * @returns {string} HTML-строка с медблоками
 */
function buildMedBlocks(yellowFlagsArray) {
  if (!yellowFlagsArray || yellowFlagsArray.length === 0) {
    return '';
  }
  
  const medContent = yellowFlagsArray
    .map(medKey => {
      const med = YELLOW_BLOCKS[medKey];
      if (!med) return '';
      return med.block;
    })
    .filter(html => html !== '')
    .join('\n');
  
  if (!medContent) return '';
  
  return `
    <div class="med-blocks-wrapper">
      ${medContent}
    </div>
  `;
}


